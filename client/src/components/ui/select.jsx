const SelectSearchInput = React.forwardRef(
  ({ className, placeholder = "Search...", value, onChange, onClear, autoFocus = true, ...props }, ref) => {
    const inputRef = React.useRef(null);

    React.useEffect(() => {
      if (autoFocus) {
        const timer = setTimeout(() => {
          inputRef.current?.focus();
        }, 30);
        return () => clearTimeout(timer);
      }
    }, [autoFocus]);

    return (
      <div
        className="select-search-wrapper"
        onPointerDown={(e) => e.stopPropagation()}
        onClick={(e) => e.stopPropagation()}
      >
        <Search className="select-search-icon" size={14} />
        <input
          ref={(node) => {
            inputRef.current = node;
            if (typeof ref === "function") ref(node);
            else if (ref) ref.current = node;
          }}
          type="text"
          className={cn("select-search-input", className)}
          placeholder={placeholder}
          value={value}
          onChange={onChange}
          onKeyDown={(e) => {
            e.stopPropagation();
            if (e.key === "ArrowDown") {
              e.preventDefault();
              const firstItem = e.currentTarget
                .closest(".select-content")
                ?.querySelector(".select-item:not([data-disabled])");
              firstItem?.focus();
            } else if (e.key === "Escape" && value) {
              e.preventDefault();
              if (onClear) onClear();
            }
          }}
          onKeyUp={(e) => e.stopPropagation()}
          {...props}
        />
        {value && (
          <button
            type="button"
            className="select-search-clear"
            onClick={(e) => {
              e.stopPropagation();
              if (onClear) onClear();
              inputRef.current?.focus();
            }}
            tabIndex={-1}
            aria-label="Clear search"
          >
            <X size={12} />
          </button>
        )}
      </div>
    );
  }
);
SelectSearchInput.displayName = "SelectSearchInput";

